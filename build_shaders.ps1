# Compiles src\shaders\*.hlsl into the headers the add-on embeds:
#   shadow_buffer.hlsl -> shadow_buffer_blobs.h, hbao_coarse.hlsl -> hbao_blobs.h.
# Needs the Windows SDK's dxc.exe (with dxil.dll beside it, so the blobs are signed).
# The generated headers are committed, so build.ps1 works without the SDK.
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot

$dxc = (Get-Command dxc.exe -ErrorAction SilentlyContinue).Source
if (-not $dxc) {
    $dxc = Get-ChildItem "${env:ProgramFiles(x86)}\Windows Kits\10\bin\*\x64\dxc.exe" -ErrorAction SilentlyContinue |
        Sort-Object FullName -Descending | Select-Object -First 1 -ExpandProperty FullName
}
if (-not $dxc) { throw "dxc.exe not found (Windows SDK). Install the Windows 10/11 SDK." }
New-Item -ItemType Directory -Force "$root\bin\shaders" | Out-Null

# Compiles each variant (name, defines) of one source into one header of byte arrays.
function Build-Header($source, $header, $variants) {
    $out = New-Object System.Text.StringBuilder
    [void]$out.AppendLine("// Generated by build_shaders.ps1 from $source - do not edit.")
    [void]$out.AppendLine('#pragma once')
    [void]$out.AppendLine('#include <cstdint>')
    foreach ($v in $variants) {
        $name, $defines = $v
        $file = "$root\bin\shaders\$name.dxil"
        $args = @('-nologo', '-T', 'ps_6_0', '-E', 'main') + ($defines | ForEach-Object { '-D', $_ })
        & $dxc @args "$root\src\shaders\$source" -Fo $file
        if ($LASTEXITCODE) { throw "shader compile failed: $name" }
        $bytes = [System.IO.File]::ReadAllBytes($file)
        # An unsigned container (all-zero digest) is rejected by D3D12: dxil.dll was missing.
        if (-not ($bytes[4..19] | Where-Object { $_ -ne 0 })) { throw "$name is unsigned - dxil.dll not found next to $dxc" }
        [void]$out.AppendLine("alignas(4) static const uint8_t k$name[$($bytes.Length)] = {")
        for ($i = 0; $i -lt $bytes.Length; $i += 24) {
            $line = ($bytes[$i..([Math]::Min($i + 23, $bytes.Length - 1))] | ForEach-Object { '0x{0:x2}' -f $_ }) -join ','
            [void]$out.AppendLine("    $line,")
        }
        [void]$out.AppendLine('};')
    }
    [System.IO.File]::WriteAllText("$root\src\shaders\$header", $out.ToString())
    Write-Host "Wrote $root\src\shaders\$header ($($variants.Count) shaders)"
}

# Shadow buffer: taps, fade in/out; the enhanced build runs the original's exact code
# until AWTweaks switches its extras on, so it ships instead of a plain rebuild.
$shadow = @()
foreach ($taps in 12, 10) {
    foreach ($start in 0, 1) {
        $base = "Sb$taps" + $(if ($start) { 'Start' } else { 'End' })
        $d = @("NUM_TAPS=$taps", "REGION_START=$start", 'ENHANCED=1')
        $shadow += , @($base, ($d + 'DEBUG_STRIPES=0'))
        $shadow += , @("${base}Debug", ($d + 'DEBUG_STRIPES=1'))
    }
}
Build-Header 'shadow_buffer.hlsl' 'shadow_buffer_blobs.h' $shadow

# HBAO+ coarse AO: 4, 6 or 8 directions; enhanced (GTAO on request, else the original code).
$hbao = @()
foreach ($dirs in 4, 6, 8) {
    $hbao += , @("AoDir$dirs", @("NUM_DIRECTIONS=$dirs", 'ENHANCED=1', 'DEBUG_STRIPES=0'))
    $hbao += , @("AoDir${dirs}Debug", @("NUM_DIRECTIONS=$dirs", 'ENHANCED=1', 'DEBUG_STRIPES=1'))
}
Build-Header 'hbao_coarse.hlsl' 'hbao_blobs.h' $hbao
